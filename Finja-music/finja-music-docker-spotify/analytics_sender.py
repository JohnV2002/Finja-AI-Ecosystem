# What this module promises (Analytics Contract 1.0):
# * Off unless ANALYTICS_ENABLED is set: no thread, no queue, no network.
# * Events are validated before they are queued; the queue is bounded and drops the oldest;
#   a retried batch keeps its event ids, a new occurrence gets a new id.
# * Only code, fingerprint, project-relative file and line of an error leave the process:
#   no message, traceback, source, prompt, user data or absolute path.
# * Expired credentials and missing settings get an `env-` fingerprint, so Flare's signal
#   gateway tells a person instead of trying to repair code.
# * Delivery problems are handed to `on_failure` once per distinct reason; the host project
#   turns them into its own Error Contract code (keep that callback a plain logger).

CONTRACT_FILE = "analytics_contract.json"
SCHEMA_VERSION = "1.0"
EVENT_ERROR = "error.occurrence"
EVENT_CPU = "system.cpu.usage"
EVENT_MEMORY = "system.memory.usage"
EVENT_LIFECYCLE = "app.lifecycle"

KINDS = {"counter", "gauge", "timing", "event", "error"}
OUTCOMES = {"success", "failure", "cancelled", "unknown"}
SAFE_TAGS = frozenset({"environment", "version", "component", "operation", "outcome"})
TOP_LEVEL_FIELDS = {
    "schema_version", "event_id", "timestamp", "project_id", "module", "event_name", "kind",
    "outcome", "value", "unit", "duration_ms", "error", "tags", "extensions",
}
ERROR_FIELDS = {"code", "fingerprint", "affected_file", "line"}
ERROR_CODE = re.compile(r"^[A-Z][A-Z0-9_]*-\d+$")
FINGERPRINT = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]{0,127}$")
EVENT_NAME = re.compile(r"^[a-z][a-z0-9_.-]{0,127}$")
PROJECT_ID_PATTERN = re.compile(r"^[a-z0-9][a-z0-9-]{0,63}$")
_FRAME = re.compile(r'File "([^"]+)", line ([1-9][0-9]*), in ([A-Za-z_<][A-Za-z0-9_<>.]{0,127})')
_SLUG = re.compile(r"[^a-z0-9._-]+")
_SKIPPED_PARTS = {".venv", "venv", "tests", "node_modules", "site-packages", "dist-packages"}

# A programming mistake is never reclassified, whatever its message says.
_PROGRAMMING_KINDS = frozenset({
    "TypeError", "ValueError", "KeyError", "AttributeError", "NameError", "IndexError", "UnboundLocalError",
    "ZeroDivisionError", "AssertionError", "NotImplementedError", "RecursionError", "ImportError",
    "ModuleNotFoundError", "SyntaxError", "IndentationError", "TabError",
})
_AUTH_TEXT = re.compile(
    r"(?i)\bHTTP\s*(?:401|403)\b|unauthori[sz]ed|forbidden|invalid[_ ]?(?:grant|token|client|credentials)|"
    r"token[- ]?refresh\s+fehlgeschlagen|refresh[_ ]token|expired|abgelaufen|authenticat|zugangsdaten")
_CONFIG_TEXT = re.compile(
    r"(?i)nicht\s+(?:gesetzt|konfiguriert)|fehlen?\s+in\s+(?:der\s+)?\.env|not\s+configured|"
    r"missing\s+\S{0,40}\s*(?:\.env|env(?:ironment)?\s+var|setting|config)|\(\.env\)")
_ENV_PREFIX = {"AuthenticationError": "env-auth", "ConfigurationError": "env-config"}
_COUNTED = "_analytics_contract_counted"

MAX_BATCH_EVENTS = 100
FLUSH_INTERVAL_SECONDS = 5.0
SAMPLE_INTERVAL_SECONDS = 60.0
MAX_BACKOFF_SECONDS = 300.0
RETRYABLE_STATUSES = {408, 425, 429}


def _slug(text: str) -> str:
    return _SLUG.sub("-", str(text).strip().casefold()).strip("-.")[:128]


# --------------------------------------------------------------------------- config

def load_contract(root: Path) -> dict[str, Any]:
    """The project's committed analytics contract; a missing or broken file means safe defaults."""
    try:
        document = json.loads((Path(root) / CONTRACT_FILE).read_text(encoding="utf-8-sig"))
    except (OSError, ValueError):
        return {}
    return document if isinstance(document, dict) else {}


@dataclass(frozen=True)
class AnalyticsConfig:
    enabled: bool
    project_id: str = "unknown-project"
    endpoint: str | None = None
    token: str | None = field(default=None, repr=False)
    environment: str = "production"
    version: str = "0.0.0"
    timeout_seconds: float = 0.75
    max_events: int = 1000
    batch_size: int = MAX_BATCH_EVENTS
    allowed_tags: frozenset[str] = SAFE_TAGS

    @property
    def events_url(self) -> str | None:
        if not self.endpoint:
            return None
        base = self.endpoint.rstrip("/")
        return base if base.endswith("/v1/events") else f"{base}/v1/events"

    @classmethod
    def from_environment(cls, root: Path, environ: Mapping[str, str] | None = None,
                         *, version: str = "0.0.0") -> tuple["AnalyticsConfig", str | None]:
        """The config and, when analytics was asked for but cannot run, why it stays off."""
        env = os.environ if environ is None else environ
        contract = load_contract(root)
        project = contract.get("project") if isinstance(contract.get("project"), dict) else {}
        analytics = contract.get("analytics") if isinstance(contract.get("analytics"), dict) else {}
        queue = analytics.get("queue") if isinstance(analytics.get("queue"), dict) else {}
        privacy = contract.get("privacy") if isinstance(contract.get("privacy"), dict) else {}
        project_id = str(project.get("id") or "")
        if not PROJECT_ID_PATTERN.fullmatch(project_id):
            return cls(enabled=False), f"{CONTRACT_FILE} has no valid project.id"
        tags = privacy.get("allowed_tags")
        allowed = frozenset(str(tag) for tag in tags) & SAFE_TAGS if isinstance(tags, list) else SAFE_TAGS
        base = cls(enabled=False, project_id=project_id, allowed_tags=allowed or SAFE_TAGS)
        wanted = str(env.get("ANALYTICS_ENABLED") or "").strip().casefold() in {"1", "true", "yes", "on"}
        if not wanted:
            return base, None
        endpoint = str(env.get(str(analytics.get("endpoint_env") or "ANALYTICS_ENDPOINT")) or "").strip()
        token = str(env.get(str(analytics.get("auth_token_env") or "ANALYTICS_TOKEN")) or "").strip()
        parsed = urllib.parse.urlparse(endpoint)
        if parsed.scheme not in {"http", "https"} or not parsed.hostname or parsed.username or parsed.password:
            return base, "the analytics endpoint must be an http(s) URL without credentials"
        if not token:
            return base, "the analytics ingest token is missing"
        timeout_ms = analytics.get("timeout_ms", 750)
        return cls(
            enabled=True, project_id=project_id, endpoint=endpoint, token=token,
            environment=_slug(str(env.get("ANALYTICS_ENVIRONMENT") or "production")) or "production",
            version=_slug(version) or "0.0.0",
            timeout_seconds=max(0.1, float(timeout_ms) / 1000) if isinstance(timeout_ms, int) else 0.75,
            max_events=max(1, int(queue.get("max_events", 1000))),
            batch_size=min(MAX_BATCH_EVENTS, max(1, int(queue.get("batch_size", MAX_BATCH_EVENTS)))),
            allowed_tags=base.allowed_tags,
        ), None


# --------------------------------------------------------------------------- validation

def _scalar_problem(value: Any, label: str) -> str | None:
    if isinstance(value, bool) or isinstance(value, (int, str)):
        if isinstance(value, str) and (len(value) > 128 or "\n" in value or "\r" in value):
            return f"{label} string must be one line and at most 128 characters"
        return None
    if isinstance(value, float):
        return None if math.isfinite(value) else f"{label} must be finite"
    return f"{label} must be a string, number, or boolean"


def validate_event(event: Mapping[str, Any], *, allowed_tags: Iterable[str] = SAFE_TAGS) -> list[str]:
    """Mirror the Analytics Contract validator and the collector's strict model."""
    if not isinstance(event, Mapping):
        return ["event must be an object"]
    problems: list[str] = []
    unknown = set(event) - TOP_LEVEL_FIELDS
    if unknown:
        problems.append(f"unknown fields: {', '.join(sorted(unknown))}")
    for key in ("schema_version", "event_id", "timestamp", "project_id", "event_name", "kind"):
        if not event.get(key):
            problems.append(f"missing {key}")
    if event.get("schema_version") != SCHEMA_VERSION:
        problems.append("schema_version must be 1.0")
    if event.get("kind") not in KINDS:
        problems.append("kind is invalid")
    if event.get("outcome") is not None and event.get("outcome") not in OUTCOMES:
        problems.append("outcome is invalid")
    if not PROJECT_ID_PATTERN.fullmatch(str(event.get("project_id") or "")):
        problems.append("project_id is invalid")
    if not EVENT_NAME.fullmatch(str(event.get("event_name") or "")):
        problems.append("event_name is invalid")
    module = event.get("module")
    if module is not None and (not isinstance(module, str) or len(module) > 128):
        problems.append("module must be a short string")
    try:
        if datetime.fromisoformat(str(event.get("timestamp"))).tzinfo is None:
            problems.append("timestamp must be timezone-aware")
    except ValueError:
        problems.append("timestamp is invalid")
    value = event.get("value")
    if value is not None and (isinstance(value, bool) or not isinstance(value, (int, float))
                              or not math.isfinite(value)):
        problems.append("value must be a finite number")
    tags = event.get("tags")
    if tags is not None and not isinstance(tags, Mapping):
        problems.append("tags must be an object")
    elif isinstance(tags, Mapping):
        disallowed = set(tags) - set(allowed_tags)
        if disallowed:
            problems.append(f"tags are not allowlisted: {', '.join(sorted(disallowed))}")
        for key, item in tags.items():
            problem = _scalar_problem(item, f"tags.{key}")
            if problem:
                problems.append(problem)
    error = event.get("error")
    if event.get("kind") == "error" and not isinstance(error, Mapping):
        problems.append("error events require an error object")
    if isinstance(error, Mapping):
        if set(error) - ERROR_FIELDS:
            problems.append("error has unknown fields")
        if not ERROR_CODE.fullmatch(str(error.get("code") or "")):
            problems.append("error.code must be PREFIX-number")
        if not FINGERPRINT.fullmatch(str(error.get("fingerprint") or "")):
            problems.append("error.fingerprint is invalid")
        affected = str(error.get("affected_file") or "").replace("\\", "/")
        pure = PurePosixPath(affected)
        if not affected:
            problems.append("error.affected_file is required")
        elif pure.is_absolute() or ":" in affected or ".." in pure.parts:
            problems.append("error.affected_file must be project-relative")
        line = error.get("line")
        if line is not None and (isinstance(line, bool) or not isinstance(line, int) or line < 1):
            problems.append("error.line must be a positive integer")
    return problems


# --------------------------------------------------------------------------- errors

def environment_kind(kind: str, cause_text: str) -> str:
    """TypeError stays TypeError; an expired token or a missing setting is named for what it is."""
    if kind in _PROGRAMMING_KINDS:
        return kind
    if _CONFIG_TEXT.search(cause_text or ""):
        return "ConfigurationError"
    if _AUTH_TEXT.search(cause_text or ""):
        return "AuthenticationError"
    return kind


def stable_fingerprint(code: str, module: str, affected_file: str, function: str, kind: str) -> str:
    """Group occurrences by code location; credentials/settings problems carry an `env-` prefix."""
    digest = hashlib.sha256(f"{code}|{module}|{affected_file}|{function}|{kind}".encode()).hexdigest()[:40]
    prefix = _ENV_PREFIX.get(kind)
    return f"{prefix}-{digest}" if prefix else digest


def _project_relative(filename: str, root: Path) -> str | None:
    candidate = Path(filename)
    if not candidate.is_absolute():
        return None
    try:
        relative = candidate.resolve().relative_to(root.resolve())
    except (OSError, ValueError):
        return None
    if not relative.parts or _SKIPPED_PARTS & set(relative.parts):
        return None
    return relative.as_posix()


def frame_from_text(traceback_text: str, root: Path) -> tuple[str, int, str] | None:
    """(project-relative file, line, function) of the deepest project frame in a formatted traceback."""
    found: tuple[str, int, str] | None = None
    for match in _FRAME.finditer(traceback_text or ""):
        relative = _project_relative(match.group(1), root)
        if relative is not None:
            found = (relative, int(match.group(2)), match.group(3))
    return found


def _chain(exception: BaseException | None) -> list[BaseException]:
    chain: list[BaseException] = []
    current, seen = exception, set()
    while current is not None and id(current) not in seen and len(chain) < 8:
        chain.append(current)
        seen.add(id(current))
        following = current.__cause__ or getattr(current, "cause", None)
        if following is None and not current.__suppress_context__:
            following = current.__context__
        current = following if isinstance(following, BaseException) else None
    return chain


def frame_from_exception(exception: BaseException | None, root: Path,
                         traceback_obj: TracebackType | None = None) -> tuple[str, int, str] | None:
    """(project-relative file, line, function) of the deepest project frame in the cause chain."""
    found: tuple[str, int, str] | None = None
    for index, item in enumerate(_chain(exception)):
        tb = traceback_obj if index == 0 and traceback_obj is not None else item.__traceback__
        for frame in traceback.extract_tb(tb) if tb is not None else ():
            relative = _project_relative(frame.filename, root)
            if relative is not None and frame.lineno:
                found = (relative, int(frame.lineno), frame.name)
    return found


