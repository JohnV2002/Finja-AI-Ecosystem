class ProcSampler:
    """CPU time and RSS of this process from /proc (Linux only, no dependency)."""

    def __init__(self, proc_self: Path = Path("/proc/self")) -> None:
        self.proc_self = proc_self
        self._ticks = float(os.sysconf("SC_CLK_TCK")) if hasattr(os, "sysconf") else 100.0
        self._page = int(os.sysconf("SC_PAGE_SIZE")) if hasattr(os, "sysconf") else 4096
        self._last: tuple[float, float] | None = None

    @staticmethod
    def supported(proc_self: Path = Path("/proc/self")) -> bool:
        return sys.platform.startswith("linux") and (proc_self / "stat").is_file()

    def cpu_percent(self, now: float | None = None) -> float | None:
        raw = (self.proc_self / "stat").read_text(encoding="ascii")
        fields = raw[raw.rindex(")") + 2:].split()
        cpu = (int(fields[11]) + int(fields[12])) / self._ticks
        wall = time.monotonic() if now is None else now
        previous, self._last = self._last, (wall, cpu)
        if previous is None or wall <= previous[0]:
            return None
        return max(0.0, (cpu - previous[1]) / (wall - previous[0]) * 100.0)

    def rss_bytes(self) -> int:
        return int((self.proc_self / "statm").read_text(encoding="ascii").split()[1]) * self._page


