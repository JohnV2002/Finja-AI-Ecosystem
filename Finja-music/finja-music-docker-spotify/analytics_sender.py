Transport = Callable[[str, bytes, dict[str, str], float], int]


def _http_post(url: str, body: bytes, headers: dict[str, str], timeout: float) -> int:
    request = urllib.request.Request(url, data=body, headers=headers, method="POST")
    try:
        with urllib.request.urlopen(request, timeout=timeout) as response:
            return int(response.status)
    except urllib.error.HTTPError as exc:
        return int(exc.code)


class AnalyticsSender:
    def __init__(self, config: AnalyticsConfig, *, root: Path, transport: Transport = _http_post,
                 sampler: ProcSampler | None = None,
                 on_failure: Callable[[dict[str, Any]], None] = lambda problem: None,
                 clock: Callable[[], float] = time.monotonic) -> None:
        self.config, self.root, self.transport = config, Path(root), transport
        self.on_failure, self.clock = on_failure, clock
        self.sampler = sampler if sampler is not None else (ProcSampler() if ProcSampler.supported() else None)
        self._queue: deque[dict[str, Any]] = deque()
        self._lock = threading.Lock()
        self._retry: list[dict[str, Any]] | None = None
        self._retry_at = 0.0
        self._backoff = FLUSH_INTERVAL_SECONDS
        self._last_problem = ""
        self._stop = threading.Event()
        self._thread: threading.Thread | None = None
        self.dropped = 0

    @property
    def enabled(self) -> bool:
        return self.config.enabled

    # -- building ---------------------------------------------------------------
    def build_event(self, event_name: str, kind: str, *, module: str | None = None, value: float | None = None,
                    unit: str | None = None, outcome: str | None = None, component: str = "runtime",
                    error: Mapping[str, Any] | None = None) -> dict[str, Any]:
        tags = {"environment": self.config.environment, "version": self.config.version, "component": component}
        event: dict[str, Any] = {
            "schema_version": SCHEMA_VERSION,
            "event_id": str(uuid.uuid4()),
            "timestamp": datetime.now(timezone.utc).isoformat(timespec="milliseconds"),
            "project_id": self.config.project_id,
            "event_name": event_name,
            "kind": kind,
            "tags": {key: item for key, item in tags.items() if key in self.config.allowed_tags},
        }
        for key, item in (("module", module), ("value", value), ("unit", unit), ("outcome", outcome)):
            if item is not None:
                event[key] = item
        if error is not None:
            event["error"] = dict(error)
        return event

    def enqueue(self, event: Mapping[str, Any]) -> bool:
        if not self.enabled or validate_event(event, allowed_tags=self.config.allowed_tags):
            return False
        with self._lock:
            if len(self._queue) >= self.config.max_events:
                self._queue.popleft()
                self.dropped += 1
            self._queue.append(dict(event))
        return True

    def queued(self) -> int:
        with self._lock:
            return len(self._queue) + len(self._retry or [])

    def _error_event(self, code: str, module: str, frame: tuple[str, int, str], kind: str) -> dict | None:
        affected_file, line, function = frame
        event = self.build_event(
            EVENT_ERROR, "error", module=_slug(module) or "app", value=1, unit="count", outcome="failure",
            component="error_contract",
            error={"code": code, "fingerprint": stable_fingerprint(code, _slug(module) or "app", affected_file,
                                                                   function, kind),
                   "affected_file": affected_file, "line": line},
        )
        return event if self.enqueue(event) else None

    # -- the three error shapes ---------------------------------------------------
    def record_dashboard_error(self, error: Mapping[str, Any]) -> dict[str, Any] | None:
        """An Error Contract `for_dashboard()` dict (code, module, cause, traceback text)."""
        code = str(error.get("code") or "")
        if not self.enabled or not ERROR_CODE.fullmatch(code) or not error.get("to_inbox", True):
            return None
        frame = frame_from_text(str(error.get("traceback") or ""), self.root)
        if frame is None:
            return None  # without a project code location there is nothing to group or repair
        cause_text = str(error.get("cause") or "")
        cause = cause_text.split(":", 1)[0].strip()
        kind = environment_kind(cause if re.fullmatch(r"[A-Za-z][A-Za-z0-9_]{0,63}", cause) else "RuntimeError",
                                cause_text)
        return self._error_event(code, str(error.get("module") or ""), frame, kind)

    def record_exception(self, exception: BaseException, *, code: str | None = None, module: str | None = None,
                         traceback_obj: TracebackType | None = None) -> dict[str, Any] | None:
        """A live exception; its own `.code` is used when no code is given. One event per cause chain."""
        code = code or str(getattr(exception, "code", "") or "")
        if not self.enabled or not ERROR_CODE.fullmatch(code) or getattr(exception, "to_inbox", True) is False:
            return None
        chain = _chain(exception)
        if any(getattr(item, _COUNTED, False) for item in chain):
            return None  # a wrapper and its cause are one occurrence
        for item in chain:
            # Marked on the object itself: ids are reused after garbage collection, a mark is not.
            try:
                setattr(item, _COUNTED, True)
            except (AttributeError, TypeError):
                pass  # an exception without __dict__ can only be counted, not marked
        frame = frame_from_exception(exception, self.root, traceback_obj)
        if frame is None:
            return None
        cause = chain[-1]
        kind = environment_kind(type(cause).__name__, f"{type(cause).__name__}: {cause}")
        return self._error_event(code, module or str(getattr(exception, "module", "") or ""), frame, kind)

    def fan_out(self, sink: Callable[[dict[str, Any]], Any]) -> Callable[[dict[str, Any]], Any]:
        """An existing error sink plus this sender; disabled analytics hands the sink back untouched."""
        if not self.enabled:
            return sink

        def both(error: dict[str, Any]) -> Any:
            result = sink(error)
            try:
                self.record_dashboard_error(error)
            except (TypeError, ValueError, KeyError, AttributeError, OSError) as exc:
                # A malformed error record must never break the project's own error reporting.
                self._fail({"reason": type(exc).__name__, "retry": False,
                            "message": "an error could not be turned into an analytics event"})
            return result

        return both

    def lifecycle(self, phase: str) -> None:
        self.enqueue(self.build_event(EVENT_LIFECYCLE, "event", value=1, unit="event", component=_slug(phase)))

    def sample_resources(self, now: float | None = None) -> int:
        if not self.enabled or self.sampler is None:
            return 0
        try:
            cpu = self.sampler.cpu_percent(now)
            rss = self.sampler.rss_bytes()
        except (OSError, ValueError, IndexError):
            return 0
        queued = 0
        if cpu is not None:
            queued += self.enqueue(self.build_event(EVENT_CPU, "gauge", value=round(cpu, 3), unit="percent",
                                                    component="process"))
        queued += self.enqueue(self.build_event(EVENT_MEMORY, "gauge", value=float(rss), unit="bytes",
                                                component="process"))
        return queued

    # -- delivery ---------------------------------------------------------------------
    def _fail(self, problem: dict[str, Any]) -> None:
        reason = str(problem.get("reason", ""))
        if reason != self._last_problem:  # once per distinct problem, not once per batch
            self._last_problem = reason
            self.on_failure(problem)  # the host logs it with its own Error Contract code

    def flush_once(self) -> int:
        """Send queued events in batches; returns how many were delivered."""
        if not self.enabled:
            return 0
        delivered = 0
        for _ in range(10):
            if self._retry is not None:
                if self.clock() < self._retry_at:
                    return delivered
                batch = self._retry
            else:
                with self._lock:
                    batch = [self._queue.popleft() for _ in range(min(self.config.batch_size, len(self._queue)))]
                if not batch:
                    return delivered
            status = self._send(batch)
            if status is not None and 200 <= status < 300:
                delivered += len(batch)
                self._retry, self._backoff, self._last_problem = None, FLUSH_INTERVAL_SECONDS, ""
                continue
            if status is None or status >= 500 or status in RETRYABLE_STATUSES:
                # Same events, same ids: the collector deduplicates a retry.
                self._retry, self._retry_at = batch, self.clock() + self._backoff
                self._backoff = min(MAX_BACKOFF_SECONDS, self._backoff * 2)
                self._fail({"reason": f"status_{status}" if status else "unreachable", "retry": True,
                            "message": "analytics batch was not delivered"})
                return delivered
            self._retry = None  # a refused batch will not become valid by retrying
            self._fail({"reason": f"status_{status}", "retry": False,
                        "message": "the collector refused an analytics batch"})
        return delivered

    def _send(self, batch: list[dict[str, Any]]) -> int | None:
        url = self.config.events_url
        if url is None:
            return None
        body = json.dumps({"events": batch}, separators=(",", ":")).encode("utf-8")
        headers = {"Content-Type": "application/json", "Authorization": f"Bearer {self.config.token}"}
        try:
            return self.transport(url, body, headers, self.config.timeout_seconds)
        except (urllib.error.URLError, OSError, ValueError):
            return None

    def start(self) -> None:
        if not self.enabled or self._thread is not None:
            return
        self.lifecycle("start")

        def run() -> None:
            next_sample = 0.0
            while not self._stop.wait(FLUSH_INTERVAL_SECONDS):
                if self.clock() >= next_sample:
                    self.sample_resources()
                    next_sample = self.clock() + SAMPLE_INTERVAL_SECONDS
                self.flush_once()

        self._thread = threading.Thread(target=run, name="analytics-sender", daemon=True)
        self._thread.start()

    def stop(self) -> None:
        if self._thread is None:
            return
        self.lifecycle("stop")
        self._stop.set()
        self.flush_once()


class AnalyticsLogHandler(logging.Handler):
    """Turns ERROR log records that carry an exception with an Error Contract code into events."""

    def __init__(self, sender: AnalyticsSender, level: int = logging.ERROR) -> None:
        super().__init__(level)
        self.sender = sender

    def emit(self, record: logging.LogRecord) -> None:
        if not self.sender.enabled or not record.exc_info or record.exc_info[1] is None:
            return
        try:
            self.sender.record_exception(record.exc_info[1], code=getattr(record, "error_code", None),
                                         traceback_obj=record.exc_info[2])
        except (TypeError, ValueError, AttributeError, OSError):
            self.handleError(record)  # logging's own path for a handler that could not emit
