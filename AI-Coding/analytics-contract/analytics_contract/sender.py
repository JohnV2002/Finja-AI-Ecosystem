from __future__ import annotations

import re
from pathlib import Path

from . import __version__

LANGUAGES = {"python": "sender_template.py"}
BODY_MARKER = "# --- sender body (everything below is copied into the project) ---"
_VERSION = re.compile(r"^\d+\.\d+\.\d+$")


class SenderError(ValueError):
    """The sender cannot be written as asked (unknown language, bad version, existing file)."""


def render_sender(*, language: str, project_name: str, module: str, version: str) -> str:
    template = LANGUAGES.get(language)
    if template is None:
        raise SenderError(
            f"no {language} sender yet; available: {', '.join(sorted(LANGUAGES))}. "
            "A new language gets its template when its first project is onboarded."
        )
    if not _VERSION.fullmatch(version):
        raise SenderError("version must be MAJOR.FEATURES.BUGS, for example 1.0.0")
    source = (Path(__file__).with_name(template)).read_text(encoding="utf-8")
    _, marker, body = source.partition(BODY_MARKER)
    if not marker:
        raise SenderError("sender template is damaged (body marker missing)")
    header = (
        '"""\n'
        f"Project: {project_name}\n"
        f"Module: {module}\n"
        "Author: J. Apps (JohnV2002 / Sodakiller1)\n"
        f"Version: {version}\n"
        "Description: Analytics Contract sender: errors, CPU and RAM to the Analytics Collector,\n"
        "    off by default, fail-silent, privacy-safe.\n"
        f"New in v{version}: Generated by analytics-contract {__version__} (`analytics-contract sender`).\n"
        "Copyright (c) 2026 J. Apps. Licensed under the MIT License.\n"
        '"""'
    )
    return header + body


def write_sender(project_root: str | Path, *, language: str, out: str | None, project_name: str,
                 version: str, force: bool = False) -> Path:
    root = Path(project_root).expanduser().resolve()
    target = (root / (out or "analytics_sender.py")).resolve()
    if root not in target.parents:
        raise SenderError("the sender must be written inside the project")
    if target.exists() and not force:
        raise SenderError(f"{target.relative_to(root).as_posix()} exists; pass --force to replace it")
    module = target.relative_to(root).with_suffix("").as_posix().replace("/", ".")
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(render_sender(language=language, project_name=project_name, module=module,
                                    version=version), encoding="utf-8", newline="\n")
    return target
